#!/usr/bin/env python3
"""Post-hoc self-evaluation of finished meetings by the participants themselves.

Each participant is re-instantiated with the same persona and LLM used during
the meeting (recorded by run-meetings), and asked to score the final adopted
itinerary against their own goals and preferences (1-10, with a reason).

Usage (via make):
    make post-eval MEETING=kyoto_tours.json RESULTS=kyoto_results.json OUTPUT=kyoto_eval.json

Usage (direct):
    python -m tour_meeting.post_eval kyoto_tours.json kyoto_results.json --output kyoto_eval.json
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from typing import Any, Dict, List

from .cli import build_meeting


def _format_route_text(destinations: List[Dict[str, Any]]) -> str:
    """Format route destinations as a detailed numbered list."""
    lines: List[str] = []
    for i, d in enumerate(destinations, 1):
        line = f"{i}. {d.get('name', 'Unknown')}"
        parts: List[str] = []
        if d.get("travel_time_from_previous"):
            parts.append(f"travel from previous: {d['travel_time_from_previous']} min")
        if d.get("stay_duration"):
            parts.append(f"stay: {d['stay_duration']} min")
        if d.get("cost"):
            parts.append(f"cost: {d['cost']}")
        if d.get("description"):
            parts.append(str(d["description"]))
        if parts:
            line += " (" + "; ".join(parts) + ")"
        lines.append(line)
    return "\n".join(lines)


async def _evaluate_all(participants: List[Any], route_text: str) -> List[Dict[str, Any]]:
    """Ask every participant to evaluate the final route concurrently."""
    results = await asyncio.gather(
        *[p.evaluate_final_route(route_text) for p in participants],
        return_exceptions=True,
    )

    evaluations: List[Dict[str, Any]] = []
    for participant, result in zip(participants, results):
        if isinstance(result, Exception):
            print(f"[!] Evaluation failed for {participant.name}: {result}", file=sys.stderr)
            evaluations.append({
                "name": participant.name,
                "score": None,
                "reason": f"Evaluation failed: {result}",
            })
        else:
            evaluations.append({
                "name": participant.name,
                "score": result["score"],
                "reason": result["reason"],
            })
    return evaluations


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Post-hoc self-evaluation of finished meetings by the participants"
    )
    parser.add_argument(
        "meeting",
        help="JSON file generated by gen-meetings (meeting definitions)",
    )
    parser.add_argument(
        "results",
        help="JSON file produced by run-meetings (analytics of finished meetings)",
    )
    parser.add_argument(
        "--output", "-o",
        required=True,
        help="JSON file to save the evaluations to",
    )
    parser.add_argument(
        "--index",
        type=int,
        default=None,
        help="Evaluate only the meeting at this index (0-based; default: evaluate all)",
    )
    args = parser.parse_args()

    # Confirm before overwriting an existing output file
    if os.path.exists(args.output):
        if sys.stdin.isatty():
            answer = input(f"[?] Output file '{args.output}' already exists. Overwrite? [y/N]: ")
            if answer.strip().lower() not in ("y", "yes"):
                print("[!] Aborted.", file=sys.stderr)
                sys.exit(1)
        else:
            print(f"[!] Output file '{args.output}' already exists. "
                  "Refusing to overwrite in non-interactive mode. "
                  "Choose a different OUTPUT file or remove the existing one.", file=sys.stderr)
            sys.exit(1)

    def _load(path: str) -> Dict[str, Any]:
        try:
            with open(path, encoding="utf-8") as f:
                return json.load(f)
        except FileNotFoundError:
            print(f"[!] File not found: {path}", file=sys.stderr)
            sys.exit(1)
        except json.JSONDecodeError as e:
            print(f"[!] Failed to parse {path}: {e}", file=sys.stderr)
            sys.exit(1)

    meeting_configs: List[Dict[str, Any]] = _load(args.meeting).get("meetings", [])
    result_entries: List[Dict[str, Any]] = _load(args.results).get("meetings", [])

    if not meeting_configs:
        print(f"[!] No meetings found in {args.meeting}", file=sys.stderr)
        sys.exit(1)
    if not result_entries:
        print(f"[!] No results found in {args.results}", file=sys.stderr)
        sys.exit(1)

    if args.index is not None:
        result_entries = [e for e in result_entries if e.get("index") == args.index]
        if not result_entries:
            print(f"[!] No result with index {args.index} in {args.results}", file=sys.stderr)
            sys.exit(1)

    all_evaluations: List[Dict[str, Any]] = []

    print(f"[+] Post-evaluating {len(result_entries)} meeting(s) ...", file=sys.stderr)

    for entry in result_entries:
        i = entry.get("index", 0)
        if not 0 <= i < len(meeting_configs):
            print(f"[!] Result index {i} has no matching meeting in {args.meeting}, skipping",
                  file=sys.stderr)
            continue
        config = meeting_configs[i]

        snapshots = (
            entry.get("analytics", {}).get("route_characteristics", {}).get("route_snapshots") or []
        )
        if not snapshots:
            print(f"[!] Meeting {i}: \"{config['title']}\" has no adopted route, skipping",
                  file=sys.stderr)
            continue
        route_text = _format_route_text(snapshots[-1].get("destinations", []))

        # Re-instantiate participants with the personas from the meeting file
        # and the runtime settings (model, temperature, seed) recorded by
        # run-meetings.
        runtime = {p["name"]: p for p in entry.get("participants", [])}
        participants: List[Dict[str, Any]] = []
        for cfg in config["participants"]:
            recorded = runtime.get(cfg["name"], {})
            model_name = recorded.get("model_name")
            if not model_name:
                print(f"[!] Meeting {i}: no model recorded for participant "
                      f"'{cfg['name']}' in {args.results}. Re-run the meetings "
                      "with the current run-meetings to record model assignments.",
                      file=sys.stderr)
                sys.exit(1)
            participants.append({
                **cfg,
                "model_name": model_name,
                "temperature": recorded.get("temperature", 0.7),
                "seed": recorded.get("seed", 42),
            })

        meeting = build_meeting(
            title=config["title"],
            global_goals=config["global_goals"],
            participants=participants,
            constraints=config.get("constraints"),
            settings=None,
        )

        print(f"\n[+] ===== Meeting {i}: {config['title']} =====", file=sys.stderr)
        evaluations = asyncio.run(_evaluate_all(meeting.participants, route_text))
        for e in evaluations:
            score = e["score"] if e["score"] is not None else "N/A"
            print(f"    {e['name']}: {score}/10 - {e['reason'][:80]}", file=sys.stderr)

        all_evaluations.append({
            "index": i,
            "title": config["title"],
            "evaluations": evaluations,
        })
        with open(args.output, "w", encoding="utf-8") as f:
            json.dump({"meetings": all_evaluations}, f, indent=2, ensure_ascii=False)
        print(f"[+] Saved evaluations to {args.output} ({len(all_evaluations)} meeting(s))",
              file=sys.stderr)


if __name__ == "__main__":
    main()
