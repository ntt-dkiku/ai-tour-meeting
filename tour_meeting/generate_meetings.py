#!/usr/bin/env python3
"""Generate tour meeting scenarios via LLM from a text instruction.

Usage (via make):
    make gen-meetings INSTRUCTION="3 people touring Kyoto" GEN_MODEL=openai/gpt-4o-mini
    make gen-meetings INSTRUCTION="Barcelona food tour" GEN_MODEL=openai/gpt-4o-mini NUM_MEETINGS=5 NUM_PARTICIPANTS=4
    make gen-meetings INSTRUCTION="Tokyo tour" GEN_MODEL=openai/gpt-4o-mini OUTPUT=configs.json

Usage (direct):
    python -m tour_meeting.generate_meetings "3 people touring Kyoto" --gen-model openai/gpt-4o-mini
    python -m tour_meeting.generate_meetings "Barcelona tour" --gen-model openai/gpt-4o-mini -n 5 -p 4
    python -m tour_meeting.generate_meetings "NYC tour" --gen-model openai/gpt-4o-mini -o configs.json
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
from typing import Any, Dict, List, Literal

from pydantic import BaseModel, Field, ValidationError

from .llm import build_litellm_kwargs, extract_json, get_format_instructions, load_llm

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Pydantic models for strict LLM output validation
# ---------------------------------------------------------------------------


class GeneratedParticipant(BaseModel):
    """A single participant generated by the LLM."""
    name: str = Field(description="Participant's name.")
    background: str = Field(description="Relevant context, experience, or situation.")
    personality: str = Field(description="Stable traits, e.g. cautious, curious, analytical, sociable.")
    preferences: str = Field(description="Likes, dislikes, priorities, and constraints.")
    personal_goals: str = Field(description="Specific goals/preferences for the tour.")
    role: Literal["facilitator", "attendee"] = Field(
        description="Role in the meeting: 'facilitator' or 'attendee'."
    )
    speaking_style: str = Field(description="Tone style (e.g. 'friendly', 'enthusiastic').")
    explanation_style: Literal["auto", "subjective", "contrastive", "both"] = Field(
        description="Explanation style: one of 'auto', 'subjective', 'contrastive', 'both'."
    )


class GeneratedMeeting(BaseModel):
    """Complete meeting scenario generated by the LLM."""
    title: str = Field(description="Meeting title.")
    global_goal: str = Field(description="Meeting objective including city name.")
    participants: list[GeneratedParticipant] = Field(
        description="List of participants for the meeting."
    )


class SupplementParticipants(BaseModel):
    """Supplementary participants generated to fill the gap."""
    participants: list[GeneratedParticipant] = Field(
        description="Additional participants to add."
    )


# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

_SYSTEM_PROMPT = """\
You are a tour meeting scenario generator.

Requirements:
1. Create a compelling meeting title
2. Define an abstract global goal for planning a ONE-DAY tour in a city
   - Always include the city name in the global goal
3. Create exactly {num_participants} participants. No more, no less.
4. Each participant should have:
   - name
   - background (relevant context, experience, or situation)
   - personality (stable traits, e.g. cautious, curious, analytical, sociable)
   - preferences (likes, dislikes, priorities, and constraints)
   - personal_goals (specific goals/preferences for the tour)
   - role: "facilitator" or "attendee" (at most ONE facilitator per meeting)
   - speaking_style (e.g. "friendly", "enthusiastic", "analytical", "supportive")
   - explanation_style: one of ["auto", "subjective", "contrastive", "both"]
5. Preference composition across participants:
{alignment_block}

Generate varied and creative scenarios."""

# Instruction blocks controlling how participants' preferences relate to each
# other. Keys are the CLI-facing alignment levels.
_ALIGNMENT_BLOCKS: Dict[str, str] = {
    "aligned": """\
   - All participants share the same overall interests and priorities.
   - Their preferences and personal goals point in the same direction and are mutually compatible; they differ only in nuance or emphasis (e.g. all are history lovers with slightly different favorite eras).
   - Avoid introducing competing priorities or constraints.
   - Even so, keep each participant's personal_goals CONCRETE: name specific place types, activities, or experiences they want (e.g. "visit a Zen temple garden", "try a traditional tea house"), not vague wishes like "have a pleasant day".""",

    "mixed": """\
   - Participants' preferences partially overlap: some interests are shared, others are individual and differ, but they can plausibly coexist within a single day with some negotiation over time and ordering.
   - Make each participant's preferences distinct.
   - Keep each participant's personal_goals CONCRETE: name specific place types, activities, or experiences they want (e.g. "visit a Zen temple garden", "try a traditional tea house"), not vague wishes like "have a pleasant day".""",

    "conflicting": """\
   - Participants' preferences and personal goals must genuinely CONFLICT: include mutually exclusive priorities that CANNOT all be satisfied in a single day, so that satisfying one participant's top priority forces a real sacrifice from another.
   - Use concrete tensions, e.g.: slow immersive pace vs. packed itinerary; quiet cultural sites vs. lively crowded areas; strict low budget vs. upscale experiences; early-morning start vs. late-night focus; staying in one district vs. covering the whole city.
   - Do NOT make the conflicts trivially resolvable, and do NOT resolve them yourself; the discussion is where trade-offs get negotiated.
   - Keep each participant's personal_goals CONCRETE: name specific place types, activities, or experiences they want (e.g. "visit a Zen temple garden", "try a traditional tea house"), not vague wishes like "have a pleasant day".""",
}

_USER_PROMPT = """\
{context_block}\
# User instructions: {instruction}

# Output Format
{format_instructions}"""


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _truncate_for_retry_context(text: str, max_len: int = 3000) -> str:
    """Truncate text for inclusion in retry error context."""
    value = (text or "").strip()
    if len(value) <= max_len:
        return value
    return value[: max_len - 3].rstrip() + "..."


def _enforce_facilitator_limit(participants: List[Dict[str, Any]]) -> None:
    """Ensure at most one facilitator exists (mutates in place).

    If multiple facilitators are found, only the first one keeps the role.
    """
    found = False
    for p in participants:
        if p["role"] == "facilitator":
            if found:
                p["role"] = "attendee"
            else:
                found = True


def _llm_call(llm_kwargs: dict, messages: list[dict[str, str]]) -> str:
    """Single litellm.completion call, returns content string."""
    import litellm as _litellm
    resp = _litellm.completion(messages=messages, **llm_kwargs)
    return resp.choices[0].message.content or ""


